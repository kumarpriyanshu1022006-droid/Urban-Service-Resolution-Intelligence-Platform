import React, { useState } from 'react';
import PredictionForm from '../components/forms/PredictionForm';
import PredictionResultCard from '../components/forms/PredictionResultCard';
import Notice from '../components/ui/Notice';
import Card from '../components/ui/Card';
import { predictResolutionTime } from '../services/api';


export default function PredictResolution({ apiHealth, initialData }) {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [validationDetails, setValidationDetails] = useState(null);
  const [result, setResult] = useState(null);
  const [lastRequestPayload, setLastRequestPayload] = useState(null);

  const handlePredictSubmit = async (formData) => {
    if (loading) return;
    setLoading(true);
    setError(null);
    setValidationDetails(null);
    setLastRequestPayload(formData);

    const response = await predictResolutionTime(formData);

    if (response.success && response.data) {
      setResult(response.data);
      setTimeout(() => {
        const resultElem = document.getElementById('prediction-result');
        if (resultElem) {
          resultElem.scrollIntoView({ behavior: 'smooth' });
        } else {
          window.scrollTo({ top: 0, behavior: 'smooth' });
        }
      }, 50);
    } else {
      setError(response.error || 'Prediction calculation failed.');
      setValidationDetails(response.validationDetails);
    }

    setLoading(false);
  };

  return (
    <div className="space-y-6">
      {/* Page Header */}
      <div className="pb-2 border-b border-[#DCDDD4]">
        <span className="text-xs font-semibold uppercase tracking-wider text-[#68716A]">
          Predictive Decision Support
        </span>
        <h1 className="text-2xl sm:text-3xl font-serif font-normal text-[#252C29] mt-0.5">
          Estimate resolution time
        </h1>
        <p className="text-xs sm:text-sm text-[#68716A] mt-1">
          Enter the details of a service request to estimate how long resolution may take.
        </p>
      </div>

      {/* Backend Health Check Alert if offline */}
      {!apiHealth?.success && (
        <Notice
          variant="warning"
          title="FastAPI Service Unreachable"
        >
          The prediction backend is currently unreachable at <code>http://127.0.0.1:8000</code>. Ensure that the FastAPI server is running with <code>uvicorn api.main:app --port 8000</code> before submitting requests.
        </Notice>
      )}

      {/* Prediction Result Display */}
      {result && (
        <div id="prediction-result">
          <PredictionResultCard
            result={result}
            requestPayload={lastRequestPayload}
          />
        </div>
      )}

      {/* Prediction Form Container */}
      <Card
        title="Service Request Parameters"
        subtitle="Provide all relevant administrative and geographic attributes for ML evaluation"
      >
        <PredictionForm
          onSubmit={handlePredictSubmit}
          loading={loading}
          error={error}
          validationDetails={validationDetails}
          initialData={initialData}
        />
      </Card>

      {/* Explanatory Operational Notice */}
      <div className="p-4 bg-[#ECEAE2]/40 rounded-lg border border-[#DCDDD4] text-xs text-[#68716A] leading-relaxed">
        <p className="font-semibold text-[#252C29] mb-1">
          Operational Usage Guidelines:
        </p>
        <p>
          Estimates generated by this tool reflect statistical distributions from historical closed complaints. Because actual field operations are subject to severe weather, emergency re-deployments, and contractor schedules, this estimate serves as an advisory benchmark for workload planning rather than an enforceable SLA contract.
        </p>
      </div>
    </div>
  );
}
